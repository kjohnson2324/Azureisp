/// <reference types="node" />
// Generates and validates the seeded case library.
//
//   npx tsx scripts/build-missions.ts          (npm run missions:build)
//
// Inputs:  content/countries/dist/countries.json, content/missions/source/*, content/samples/*.json
// Outputs: content/missions/dist/missions.json   bundled with the app (offline play)
//          supabase/seed_missions.sql            loaded after seed.sql
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

import { ContentEnvelope, Mission, type Country } from '../src/content/schemas';
import { countryPool, generateAllMissions } from '../src/features/missions/generator';
import { VILLAINS } from '../content/missions/source/villains';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const countries: Country[] = JSON.parse(readFileSync(join(root, 'content/countries/dist/countries.json'), 'utf8'));
const sample = JSON.parse(readFileSync(join(root, 'content/samples/mission.vanishing-tower.json'), 'utf8')).mission;
const clueIds = new Set(countries.flatMap((c) => c.clues.map((k) => k.id)));

const missions = [...generateAllMissions(countries), { ...sample, data: Mission.parse(sample.data) }];
const errors: string[] = [];
for (const m of missions) {
  ContentEnvelope.parse(m);
  const parsed = Mission.safeParse(m.data);
  if (!parsed.success) { errors.push(`${m.id}: ${parsed.error.issues.map((i) => i.message).join('; ')}`); continue; }
  const d = parsed.data;
  if (m.grade_bands.length === 0 || m.standard_ids.length === 0) errors.push(`${m.id}: missing grade band or standards`);
  const route = d.stops.map((s) => s.country);
  if (new Set(route).size !== route.length) errors.push(`${m.id}: route revisits a country`);
  for (const s of d.stops) for (const id of s.clueIds) if (!clueIds.has(id)) errors.push(`${m.id}: unknown clue ${id}`);
  for (const s of d.stops) if (s.choices && new Set(s.choices).size !== s.choices.length) errors.push(`${m.id}: duplicate choices`);
  // Hints must not contain the answer's name.
  for (const [i, st] of d.stops.entries()) {
    const next = d.stops[i + 1];
    if (!next) continue;
    const c = countries.find((x) => x.iso2 === next.country)!;
    if (st.hint.en.toLowerCase().includes(c.name.en.toLowerCase()) || st.hint.es.toLowerCase().includes(c.name.es.toLowerCase())) {
      errors.push(`${m.id}: hint at stop ${i + 1} names the answer`);
    }
  }
  // Every dossier trait must belong to the culprit and no other suspect.
  const own = new Set(VILLAINS[d.culprit].traits.map((t) => t[0]));
  for (const c of d.culpritClues) if (!own.has(c.en) && m.id !== sample.id) errors.push(`${m.id}: trait not owned by culprit`);
}
for (const m of missions.filter((x) => x.id !== sample.id)) {
  const band = m.grade_bands[0]!;
  const pool = new Set(countryPool(band, countries).map((c) => c.iso2));
  const d = m.data as { stops: { country: string; choices?: string[] }[]; landmark: { country: string } };
  for (const s of d.stops) {
    for (const iso of [s.country, ...(s.choices ?? [])]) {
      if (iso !== d.landmark.country && !pool.has(iso)) errors.push(`${m.id}: ${iso} is outside the ${band} country pool`);
    }
  }
}
const ids = missions.map((m) => m.id);
if (new Set(ids).size !== ids.length) errors.push('duplicate mission ids');
if (errors.length) {
  console.error(`✖ ${errors.length} problem(s):\n  ${errors.join('\n  ')}`);
  process.exit(1);
}

mkdirSync(join(root, 'content/missions/dist'), { recursive: true });
writeFileSync(join(root, 'content/missions/dist/missions.json'), JSON.stringify(missions) + '\n');

const q = (s: string) => `'${s.replace(/'/g, "''")}'`;
const arr = (xs: readonly string[]) => `'{${xs.join(',')}}'`;
writeFileSync(join(root, 'supabase/seed_missions.sql'), [
  '-- GENERATED by scripts/build-missions.ts. Do not edit by hand.',
  'begin;',
  'insert into public.content_items (id, version, kind, status, grade_bands, standard_ids, country_codes, data) values',
  missions.map((m) => `  (${q(m.id)}, ${m.version}, 'mission', 'published', ${arr(m.grade_bands)}, ${arr(m.standard_ids)}, ${arr(m.country_codes)}, ${q(JSON.stringify(m.data))}::jsonb)`).join(',\n'),
  'on conflict (id, version) do nothing;',
  'commit;',
  '',
].join('\n'));

const per = (b: string) => missions.filter((m) => m.grade_bands.includes(b as never)).length;
console.log(`✔ ${missions.length} missions (K-2: ${per('K-2')}, 3-5: ${per('3-5')}, 6-8: ${per('6-8')})`);
